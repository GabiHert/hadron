package actions

import (
	"fmt"
	"sort"
	"strings"
)

// ToolsDoc renders every registered action as the Markdown of docs/mcp-tools.md: the same list the
// MCP server offers as tools, so the README never drifts from the code. A test keeps the file
// current, and `go run ./cmd/toolsdoc` rewrites it.
func ToolsDoc(r *Registry) string {
	groups := map[string][]Info{}
	for _, in := range r.Infos() {
		g := toolGroup(in.Name)
		groups[g] = append(groups[g], in)
	}
	names := make([]string, 0, len(groups))
	for g := range groups {
		names = append(names, g)
	}
	sort.Strings(names)

	var b strings.Builder
	fmt.Fprintf(&b, "# Hadron MCP tools\n\n")
	fmt.Fprintf(&b, "<!-- Generated by `go run ./cmd/toolsdoc` from the action registry. Do not edit by hand. -->\n\n")
	fmt.Fprintf(&b, "Hadron serves %d tools, one per action. Everything you can do in the app is also a tool, so a Claude\n", r.Len())
	fmt.Fprintf(&b, "that you connect can drive the board the way you do. Tools marked **changes data** write to the\n")
	fmt.Fprintf(&b, "store; the others only read. See the README for how to connect.\n\n")
	fmt.Fprintf(&b, "Groups: ")
	for i, g := range names {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "[%s](#%s) (%d)", g, g, len(groups[g]))
	}
	b.WriteString("\n")
	for _, g := range names {
		fmt.Fprintf(&b, "\n## %s\n", g)
		for _, in := range groups[g] {
			kind := "reads"
			if in.Mutates {
				kind = "changes data"
			}
			fmt.Fprintf(&b, "\n### `%s`\n\n%s\n\n*%s*\n", in.Name, in.Description, kind)
			if len(in.Fields) == 0 {
				fmt.Fprintf(&b, "\nNo arguments.\n")
				continue
			}
			fmt.Fprintf(&b, "\n| Argument | Type | Required | What it is |\n|---|---|---|---|\n")
			for _, f := range in.Fields {
				req := "no"
				if f.Required {
					req = "yes"
				}
				fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", f.Name, f.Type, req, strings.ReplaceAll(f.Description, "|", "\\|"))
			}
		}
	}
	return b.String()
}

// toolGroup names the group of a tool: its first word, except for the few that read better together.
func toolGroup(name string) string {
	switch name {
	case "check_for_update", "get_update_status", "start_update", "set_update_token":
		return "update"
	case "notify", "settings_get", "settings_update", "app_status", "mcp_calls", "mcp_info":
		return "app"
	case "widget_post", "widget_pin":
		return "widget"
	}
	g, _, _ := strings.Cut(name, "_")
	return g
}
